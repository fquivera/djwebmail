"""File-based mail account storage driver for docker-mailserver / Dovecot."""

from __future__ import annotations

import os
import re
import tempfile
from collections.abc import Mapping, Sequence

from django.utils.translation import gettext as _

from apps.accounts.services.password import hash_sha512_crypt
from apps.mailadmin.drivers.base import BaseMailAccountDriver, MailAccountData, MailAliasData
from apps.mailadmin.exceptions import (
    MailAccountAlreadyExistsError,
    MailAccountNotFoundError,
    MailAdminError,
    MailAliasAlreadyExistsError,
    MailAliasNotFoundError,
)

_QUOTA_RE = re.compile(r"^(\d+)\s*([KMGTP]?B?)$", re.IGNORECASE)


def parse_quota_string_to_bytes(quota_str: str) -> int | None:
    """Parse quota strings like '2048M', '5G', '100000K' into bytes."""
    quota_clean = quota_str.strip().upper()
    if not quota_clean or quota_clean in ("0", "UNLIMITED"):
        return None

    match = _QUOTA_RE.match(quota_clean)
    if not match:
        return None

    val = int(match.group(1))
    unit = match.group(2).rstrip("B")
    multipliers = {
        "": 1,
        "K": 1024,
        "M": 1024 * 1024,
        "G": 1024 * 1024 * 1024,
        "T": 1024 * 1024 * 1024 * 1024,
    }
    return val * multipliers.get(unit, 1)


def format_bytes_to_quota_string(num_bytes: int | None) -> str:
    """Format bytes into Dovecot quota specification (e.g. '2048M', '5G')."""
    if num_bytes is None:
        return ""
    if num_bytes % (1024 * 1024 * 1024) == 0:
        return f"{num_bytes // (1024 * 1024 * 1024)}G"
    return f"{num_bytes // (1024 * 1024)}M"


class FileMailAccountDriver(BaseMailAccountDriver):
    """Driver managing accounts in postfix-accounts.cf and dovecot-quotas.cf files."""

    def __init__(
        self,
        accounts_file: str,
        quotas_file: str | None = None,
        virtual_file: str | None = None,
    ) -> None:
        self.accounts_file = accounts_file
        if quotas_file:
            self.quotas_file = quotas_file
        elif accounts_file:
            file_dir = os.path.dirname(os.path.abspath(accounts_file))
            self.quotas_file = os.path.join(file_dir, "dovecot-quotas.cf")
        else:
            self.quotas_file = ""

        if virtual_file:
            self.virtual_file = virtual_file
        elif accounts_file:
            file_dir = os.path.dirname(os.path.abspath(accounts_file))
            self.virtual_file = os.path.join(file_dir, "postfix-virtual.cf")
        else:
            self.virtual_file = ""

    def _ensure_file_exists(self, file_path: str) -> None:
        if not file_path:
            raise MailAdminError(_("No accounts file path configured."))
        if not os.path.isfile(file_path):
            try:
                os.makedirs(os.path.dirname(os.path.abspath(file_path)), exist_ok=True)
                with open(file_path, "w", encoding="utf-8") as f:
                    f.write("# postfix-accounts.cf generated by DjWebmail\n")
            except OSError as exc:
                raise MailAdminError(
                    _("Failed to initialize accounts file '%(path)s': %(error)s")
                    % {"path": file_path, "error": str(exc)}
                ) from exc

    def _read_quotas(self) -> dict[str, int]:
        quotas: dict[str, int] = {}
        if not self.quotas_file or not os.path.isfile(self.quotas_file):
            return quotas

        try:
            with open(self.quotas_file, encoding="utf-8") as f:
                for raw_line in f:
                    line = raw_line.strip()
                    if not line or line.startswith("#"):
                        continue
                    if ":" in line:
                        user, q_val = line.split(":", 1)
                        b = parse_quota_string_to_bytes(q_val)
                        if b is not None:
                            quotas[user.strip().lower()] = b
        except OSError:
            pass
        return quotas

    def _write_quotas(self, quotas: Mapping[str, int | None]) -> None:
        if not self.quotas_file:
            return

        file_dir = os.path.dirname(os.path.abspath(self.quotas_file))
        os.makedirs(file_dir, exist_ok=True)

        lines: list[str] = ["# dovecot-quotas.cf generated by DjWebmail"]
        for email, q_bytes in sorted(quotas.items()):
            if q_bytes is not None:
                q_str = format_bytes_to_quota_string(q_bytes)
                if q_str:
                    lines.append(f"{email.strip().lower()}:{q_str}")

        try:
            with tempfile.NamedTemporaryFile(
                "w", dir=file_dir, encoding="utf-8", delete=False
            ) as tmp:
                tmp.write("\n".join(lines) + "\n")
                tmp_path = tmp.name
            os.replace(tmp_path, self.quotas_file)
        except OSError as exc:
            raise MailAdminError(
                _("Failed to write quotas file: %(error)s") % {"error": str(exc)}
            ) from exc

    def list_accounts(
        self,
        search: str = "",
        is_active: bool | None = None,
    ) -> list[MailAccountData]:
        self._ensure_file_exists(self.accounts_file)
        quotas = self._read_quotas()
        results: list[MailAccountData] = []
        search_lower = search.strip().lower()

        try:
            with open(self.accounts_file, encoding="utf-8") as f:
                for raw_line in f:
                    line = raw_line.strip()
                    if not line:
                        continue

                    active = True
                    if line.startswith("#"):
                        line_content = line.lstrip("#").strip()
                        # If commented line contains a pipe with email, treat as suspended
                        if "|" in line_content and "@" in line_content.split("|")[0]:
                            active = False
                            line = line_content
                        else:
                            continue

                    parts = line.split("|")
                    email = parts[0].strip().lower()
                    if "@" not in email:
                        continue

                    if is_active is not None and active != is_active:
                        continue

                    if search_lower and search_lower not in email:
                        continue

                    quota_bytes = quotas.get(email)
                    results.append(
                        MailAccountData(
                            email=email,
                            is_active=active,
                            quota_bytes=quota_bytes,
                        )
                    )
            return sorted(results, key=lambda a: a.email)
        except OSError as exc:
            raise MailAdminError(
                _("Failed to read accounts file: %(error)s") % {"error": str(exc)}
            ) from exc

    def get_account(self, email: str) -> MailAccountData | None:
        target = email.strip().lower()
        accounts = self.list_accounts()
        for acc in accounts:
            if acc.email == target:
                return acc
        return None

    def create_account(
        self,
        email: str,
        password: str,
        quota_bytes: int | None = None,
        is_active: bool = True,
    ) -> MailAccountData:
        target = email.strip().lower()
        if self.get_account(target) is not None:
            raise MailAccountAlreadyExistsError(
                _("An account with email '%(email)s' already exists.") % {"email": target}
            )

        self._ensure_file_exists(self.accounts_file)
        password_hash = hash_sha512_crypt(password)
        prefix = "" if is_active else "#"
        new_entry = f"{prefix}{target}|{password_hash}"

        file_dir = os.path.dirname(os.path.abspath(self.accounts_file))
        lines: list[str] = []
        try:
            with open(self.accounts_file, encoding="utf-8") as f:
                for raw_line in f:
                    lines.append(raw_line.rstrip("\r\n"))
            lines.append(new_entry)

            with tempfile.NamedTemporaryFile(
                "w", dir=file_dir, encoding="utf-8", delete=False
            ) as tmp:
                tmp.write("\n".join(lines) + "\n")
                tmp_path = tmp.name
            os.replace(tmp_path, self.accounts_file)
        except OSError as exc:
            raise MailAdminError(
                _("Failed to write to accounts file: %(error)s") % {"error": str(exc)}
            ) from exc

        if quota_bytes is not None:
            quotas = self._read_quotas()
            quotas[target] = quota_bytes
            self._write_quotas(quotas)

        return MailAccountData(email=target, is_active=is_active, quota_bytes=quota_bytes)

    def update_account(
        self,
        email: str,
        password: str | None = None,
        quota_bytes: int | None = None,
        is_active: bool | None = None,
        clear_quota: bool = False,
    ) -> MailAccountData:
        target = email.strip().lower()
        existing = self.get_account(target)
        if existing is None:
            raise MailAccountNotFoundError(_("Account '%(email)s' not found.") % {"email": target})

        self._ensure_file_exists(self.accounts_file)
        new_active = existing.is_active if is_active is None else is_active
        new_hash = hash_sha512_crypt(password) if password else None

        file_dir = os.path.dirname(os.path.abspath(self.accounts_file))
        lines: list[str] = []
        found = False

        try:
            with open(self.accounts_file, encoding="utf-8") as f:
                for raw_line in f:
                    line = raw_line.rstrip("\r\n")
                    clean_line = line.lstrip("#").strip()
                    parts = clean_line.split("|")
                    if parts and parts[0].strip().lower() == target:
                        current_hash = parts[1].strip() if len(parts) > 1 else ""
                        final_hash = new_hash or current_hash
                        prefix = "" if new_active else "#"
                        rest = parts[2:] if len(parts) > 2 else []
                        extra = f"|{'|'.join(rest)}" if rest else ""
                        lines.append(f"{prefix}{target}|{final_hash}{extra}")
                        found = True
                    else:
                        lines.append(line)

            if not found:
                raise MailAccountNotFoundError(
                    _("Account '%(email)s' not found.") % {"email": target}
                )

            with tempfile.NamedTemporaryFile(
                "w", dir=file_dir, encoding="utf-8", delete=False
            ) as tmp:
                tmp.write("\n".join(lines) + "\n")
                tmp_path = tmp.name
            os.replace(tmp_path, self.accounts_file)
        except OSError as exc:
            raise MailAdminError(
                _("Failed to update accounts file: %(error)s") % {"error": str(exc)}
            ) from exc

        quotas = self._read_quotas()
        if clear_quota:
            quotas.pop(target, None)
            self._write_quotas(quotas)
            final_quota = None
        elif quota_bytes is not None:
            quotas[target] = quota_bytes
            self._write_quotas(quotas)
            final_quota = quota_bytes
        else:
            final_quota = quotas.get(target)

        return MailAccountData(email=target, is_active=new_active, quota_bytes=final_quota)

    def delete_account(self, email: str) -> bool:
        target = email.strip().lower()
        self._ensure_file_exists(self.accounts_file)

        file_dir = os.path.dirname(os.path.abspath(self.accounts_file))
        lines: list[str] = []
        deleted = False

        try:
            with open(self.accounts_file, encoding="utf-8") as f:
                for raw_line in f:
                    line = raw_line.rstrip("\r\n")
                    clean_line = line.lstrip("#").strip()
                    parts = clean_line.split("|")
                    if parts and parts[0].strip().lower() == target:
                        deleted = True
                    else:
                        lines.append(line)

            if deleted:
                with tempfile.NamedTemporaryFile(
                    "w", dir=file_dir, encoding="utf-8", delete=False
                ) as tmp:
                    tmp.write("\n".join(lines) + "\n")
                    tmp_path = tmp.name
                os.replace(tmp_path, self.accounts_file)

                quotas = self._read_quotas()
                if target in quotas:
                    quotas.pop(target, None)
                    self._write_quotas(quotas)

            return deleted
        except OSError as exc:
            raise MailAdminError(
                _("Failed to delete from accounts file: %(error)s") % {"error": str(exc)}
            ) from exc

    def _ensure_virtual_file_exists(self) -> None:
        if not self.virtual_file:
            raise MailAdminError(_("No virtual aliases file path configured."))
        if not os.path.isfile(self.virtual_file):
            try:
                os.makedirs(os.path.dirname(os.path.abspath(self.virtual_file)), exist_ok=True)
                with open(self.virtual_file, "w", encoding="utf-8") as f:
                    f.write("# postfix-virtual.cf generated by DjWebmail\n")
            except OSError as exc:
                raise MailAdminError(
                    _("Failed to initialize virtual file '%(path)s': %(error)s")
                    % {"path": self.virtual_file, "error": str(exc)}
                ) from exc

    def _read_virtual_aliases(self) -> dict[str, MailAliasData]:
        aliases: dict[str, MailAliasData] = {}
        if not self.virtual_file or not os.path.isfile(self.virtual_file):
            return aliases

        try:
            with open(self.virtual_file, encoding="utf-8") as f:
                for raw_line in f:
                    line = raw_line.strip()
                    if not line:
                        continue

                    is_active = True
                    if line.startswith("#"):
                        is_active = False
                        line = line.lstrip("#").strip()

                    # Expect format: source destination1, destination2... or whitespace separated
                    parts = line.split(None, 1)
                    if len(parts) < 2:
                        continue

                    source, raw_dests = parts[0].strip().lower(), parts[1].strip()
                    if "@" not in source:
                        continue

                    # destinations can be separated by spaces or commas
                    dests = [
                        d.strip().lower() for d in raw_dests.replace(",", " ").split() if d.strip()
                    ]
                    if not dests:
                        continue

                    aliases[source] = MailAliasData(
                        source=source,
                        destinations=dests,
                        name="",
                        is_active=is_active,
                    )
            return aliases
        except OSError as exc:
            raise MailAdminError(
                _("Failed to read virtual aliases file: %(error)s") % {"error": str(exc)}
            ) from exc

    def _write_virtual_aliases(self, aliases: Mapping[str, MailAliasData]) -> None:
        self._ensure_virtual_file_exists()
        file_dir = os.path.dirname(os.path.abspath(self.virtual_file))

        lines: list[str] = ["# postfix-virtual.cf generated by DjWebmail"]
        for source in sorted(aliases.keys()):
            data = aliases[source]
            dests_str = " ".join(data.destinations)
            if data.is_active:
                lines.append(f"{data.source} {dests_str}")
            else:
                lines.append(f"# {data.source} {dests_str}")

        try:
            with tempfile.NamedTemporaryFile(
                "w", dir=file_dir, encoding="utf-8", delete=False
            ) as tmp:
                tmp.write("\n".join(lines) + "\n")
                tmp_path = tmp.name
            os.replace(tmp_path, self.virtual_file)
        except OSError as exc:
            raise MailAdminError(
                _("Failed to write virtual aliases file: %(error)s") % {"error": str(exc)}
            ) from exc

    def list_aliases(
        self,
        search: str = "",
        is_active: bool | None = None,
    ) -> list[MailAliasData]:
        aliases_dict = self._read_virtual_aliases()
        results: list[MailAliasData] = []
        term = search.strip().lower()

        for data in aliases_dict.values():
            if is_active is not None and data.is_active != is_active:
                continue
            if term:
                match_source = term in data.source.lower()
                match_dest = any(term in d.lower() for d in data.destinations)
                if not (match_source or match_dest):
                    continue
            results.append(data)

        results.sort(key=lambda a: a.source)
        return results

    def get_alias(self, source: str) -> MailAliasData | None:
        target = source.strip().lower()
        aliases_dict = self._read_virtual_aliases()
        return aliases_dict.get(target)

    def create_alias(
        self,
        source: str,
        destinations: Sequence[str],
        name: str = "",
        is_active: bool = True,
    ) -> MailAliasData:
        target = source.strip().lower()
        if not target or "@" not in target:
            raise MailAdminError(_("Invalid alias source address."))

        clean_dests = [d.strip().lower() for d in destinations if d.strip()]
        if not clean_dests:
            raise MailAdminError(_("An alias must have at least one destination address."))

        aliases = self._read_virtual_aliases()
        if target in aliases:
            raise MailAliasAlreadyExistsError(
                _("Alias '%(source)s' already exists.") % {"source": target}
            )

        new_alias = MailAliasData(
            source=target,
            destinations=clean_dests,
            name=name.strip(),
            is_active=is_active,
        )
        aliases[target] = new_alias
        self._write_virtual_aliases(aliases)
        return new_alias

    def update_alias(
        self,
        source: str,
        destinations: Sequence[str] | None = None,
        name: str | None = None,
        is_active: bool | None = None,
    ) -> MailAliasData:
        target = source.strip().lower()
        aliases = self._read_virtual_aliases()
        if target not in aliases:
            raise MailAliasNotFoundError(_("Alias '%(source)s' not found.") % {"source": target})

        current = aliases[target]
        new_dests = (
            [d.strip().lower() for d in destinations if d.strip()]
            if destinations is not None
            else current.destinations
        )
        if not new_dests:
            raise MailAdminError(_("An alias must have at least one destination address."))

        new_name = name.strip() if name is not None else current.name
        new_active = is_active if is_active is not None else current.is_active

        updated = MailAliasData(
            source=target,
            destinations=new_dests,
            name=new_name,
            is_active=new_active,
        )
        aliases[target] = updated
        self._write_virtual_aliases(aliases)
        return updated

    def delete_alias(self, source: str) -> bool:
        target = source.strip().lower()
        aliases = self._read_virtual_aliases()
        if target not in aliases:
            return False

        aliases.pop(target, None)
        self._write_virtual_aliases(aliases)
        return True
